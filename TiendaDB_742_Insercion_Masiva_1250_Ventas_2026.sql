ALTER VIEW dbo.vw_ReporteVentas
AS
SELECT 
    P.PedidoID,
    C.ClienteID,
    C.Nombre AS Cliente,
    C.Ciudad,
    C.Telefono,
    PR.ProductoID,
    PR.NombreProducto,
    PR.Precio,
    P.Cantidad,
    (PR.Precio * P.Cantidad) AS Subtotal,
    dbo.fn_CalcularImpuesto(PR.Precio * P.Cantidad) AS Impuesto,
    (PR.Precio * P.Cantidad) + dbo.fn_CalcularImpuesto(PR.Precio * P.Cantidad) AS TotalVenta,
    P.FechaPedido,
    ISNULL(V.Nombre, 'Venta Mostrador') AS Vendedor
FROM Pedidos P
INNER JOIN Clientes C ON P.ClienteID = C.ClienteID
INNER JOIN Productos PR ON P.ProductoID = PR.ProductoID
LEFT JOIN Vendedores V ON P.VendedorID = V.VendedorID;
GO